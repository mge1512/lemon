/* The main parser program.
** The first argument is a parser from ParseAlloc().  The second argument
** is the major token number.  The third is the minor token.  The fourth
** argument is the value of %extra_argument.
**
** Inputs:
** <ul>
** <li> A pointer to the parser (an opaque structure.)
** <li> The major token number.
** <li> The minor token number.
** <li> The value of %extra_argument.
** </ul>
**
** Outputs:
** None.
*/
func Parse(yypParser *yyParser, yymajor int, yyminor ParseTOKENTYPE, yyarg ParseARGTYPE) {
	yypParser.yyarg = yyarg
	yyendofinput := yymajor == 0 /* True if we are at the end of input */
	yyact := yypParser.yystack[len(yypParser.yystack)-1].stateno
	if yyTrace != nil {
		if yyact < YY_MIN_REDUCE {
			yyTrace("Input '" + yyTokenName[yymajor] + "' in state " + yyitoa(int(yyact)))
		} else {
			yyTrace("Input '" + yyTokenName[yymajor] + "' with pending reduce " + yyitoa(int(yyact)-YY_MIN_REDUCE))
		}
	}
	for { /* Exit by "break" */
		yyact = yy_find_shift_action(YYCODETYPE(yymajor), yyact)
		if yyact >= YY_MIN_REDUCE {
			yyruleno := int(yyact) - YY_MIN_REDUCE /* Reduce by this rule */
			if yyTrace != nil {
				yyTrace("Reduce " + yyitoa(yyruleno) + " [" + yyRuleName[yyruleno] + "]")
			}
			/* Check that the stack is large enough to grow by a single entry
			 ** if the RHS of the rule is empty.  This ensures that there is room
			 ** enough on the stack to push the LHS value */
			if yyRuleInfoNRhs[yyruleno] == 0 && YYSTACKDEPTH > 0 && len(yypParser.yystack) >= YYSTACKDEPTH {
				yyStackOverflow(yypParser)
				break
			}
			yyact = yy_reduce(yypParser, yyruleno, yymajor, yyminor)
		} else if yyact <= YY_MAX_SHIFTREDUCE {
			yy_shift(yypParser, yyact, YYCODETYPE(yymajor), yyminor)
			yypParser.yyerrcnt--
			break
		} else if yyact == YY_ACCEPT_ACTION {
			yypParser.yystack = yypParser.yystack[:len(yypParser.yystack)-1]
			yy_accept(yypParser)
			return
		} else {
			/* A syntax error has occurred.  This template handles it in the
			 ** way of lempar.c for a grammar without the error symbol:
			 **
			 **  * Report an error message, and throw away the input token.
			 **
			 **  * If the input token is $, then fail the parse.
			 **
			 ** As before, subsequent error messages are suppressed until
			 ** three input tokens have been successfully shifted.
			 */
			if yyTrace != nil {
				yyTrace("Syntax Error!")
			}
			if yypParser.yyerrcnt <= 0 {
				yy_syntax_error(yypParser, yymajor, yyminor)
			}
			yypParser.yyerrcnt = 3
			if yyendofinput {
				yy_parse_failed(yypParser)
				yypParser.yyerrcnt = -1
			}
			break
		}
	}
}

