/*
** Find the appropriate action for a parser given the terminal
** look-ahead token iLookAhead.
*/
func yy_find_shift_action(iLookAhead YYCODETYPE, stateno YYACTIONTYPE) YYACTIONTYPE {
	if stateno > YY_MAX_SHIFT {
		return stateno
	}
	for {
		i := int(yy_shift_ofst[stateno])
		i += int(iLookAhead)
		if yy_lookahead[i] != iLookAhead {
			if YYFALLBACK != 0 {
				iFallback := yyFallback[iLookAhead]
				if iFallback != 0 {
					if yyTrace != nil {
						yyTrace("FALLBACK " + yyTokenName[iLookAhead] + " => " + yyTokenName[iFallback])
					}
					iLookAhead = iFallback
					continue
				}
			}
			if YYWILDCARD > 0 {
				j := i - int(iLookAhead) + YYWILDCARD
				if int(yy_lookahead[j]) == YYWILDCARD && iLookAhead > 0 {
					if yyTrace != nil {
						yyTrace("WILDCARD " + yyTokenName[iLookAhead] + " => " + yyTokenName[YYWILDCARD])
					}
					return yy_action[j]
				}
			}
			return yy_default[stateno]
		}
		return yy_action[i]
	}
}

